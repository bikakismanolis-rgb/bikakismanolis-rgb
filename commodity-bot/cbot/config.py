@dataclass(frozen=True)
class Settings:
    trend_window: int = 200        # ημέρες κινητού μέσου: αγοράζουμε μόνο πάνω από αυτόν
    vol_window: int = 60           # ημέρες για εκτίμηση μεταβλητότητας
    target_vol: float = 0.10       # ετήσια μεταβλητότητα-στόχος χαρτοφυλακίου
    max_weight: float = 0.15       # μέγιστο ποσοστό κεφαλαίου ανά εμπόρευμα
    max_gross: float = 1.0         # ποτέ μόχλευση: σύνολο θέσεων <= 100%
    rebalance_every: int = 5       # κάθε πόσες συνεδριάσεις αναπροσαρμόζουμε (backtest)
    cost_bps: float = 10.0         # προμήθεια + slippage ανά συναλλαγή (0.10%)
    rebalance_band: float = 0.02   # paper: αγνόησε αποκλίσεις κάτω από 2% του κεφαλαίου
    max_drawdown: float = 0.15     # kill switch: κλείσε τα πάντα αν χαθεί 15% από το υψηλό


SETTINGS = Settings()
