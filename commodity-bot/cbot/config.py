# Διαπραγματευόμαστε μόνο τα ETCs με φυσικό μέταλλο στο θησαυροφυλάκιο. Τα υπόλοιπα
# βασίζονται σε futures και χάνουν αξία από το κόστος ανανέωσης των συμβολαίων: στο
# backtest κανένας κανόνας δεν έβγαλε κέρδος πάνω τους. Τα παρακολουθούμε μόνο.
TRADED = ["PHAU.MI", "PHAG.MI", "PHPT.MI", "PHPD.MI"]


@dataclass(frozen=True)
class Settings:
    trend_window: int = 200        # ημέρες κινητού μέσου: αγοράζουμε μόνο πάνω από αυτόν
    vol_window: int = 60           # ημέρες για εκτίμηση μεταβλητότητας
    target_vol: float = 0.10       # ετήσια μεταβλητότητα-στόχος χαρτοφυλακίου
    max_weight: float = 0.25       # μέγιστο ποσοστό κεφαλαίου ανά εμπόρευμα
    max_gross: float = 1.0         # ποτέ μόχλευση: σύνολο θέσεων <= 100%
    rebalance_every: int = 21      # κάθε πόσες συνεδριάσεις αναπροσαρμόζουμε (backtest)
    cost_bps: float = 15.0         # προμήθεια + spread ανά συναλλαγή (0.15%)
    rebalance_band: float = 0.02   # αγνόησε αποκλίσεις κάτω από 2% του κεφαλαίου
    max_drawdown: float = 0.15     # kill switch: κλείσε τα πάντα αν χαθεί 15% από το υψηλό
    max_order_value: float = 2000  # πραγματικός broker: ανώτατη αξία μίας εντολής σε ευρώ


SETTINGS = Settings()
